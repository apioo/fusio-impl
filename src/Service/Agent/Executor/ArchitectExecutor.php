namespace Fusio\Impl\Service\Agent\Executor;

use Fusio\Engine\ContextInterface;
use Fusio\Impl\Service;
use Fusio\Impl\Service\Agent\Task\StepLogger;
use Fusio\Impl\Table;
use Fusio\Model\Agent\Blueprint;
use Fusio\Model\Agent\BlueprintOperation;
use Fusio\Model\Agent\Database;
use Fusio\Model\Agent\Input;
use Fusio\Model\Agent\Item;
use Fusio\Model\Agent\ItemObject;
use Fusio\Model\Agent\ItemText;
use Fusio\Model\Agent\Schema;
use Fusio\Model\Backend\OperationCreate;
use Fusio\Model\Backend\OperationParameters;
use Fusio\Model\Backend\OperationSchema;
use Fusio\Model\Backend\OperationUpdate;
use Fusio\Model\Common\Message;
use PSX\Json\Parser;
use PSX\Schema\ObjectMapperInterface;
use PSX\Schema\SchemaSource;
use RuntimeException;
use Throwable;

/**
 * Executes a blueprint which was generated by the architect agent. This means we invoke the database agent to create
 * the tables and for every operation the schema and action agent, at the end we create or update the operation. The
 * sub-agents can be configured through the metadata of the architect agent i.e. {"schemaAgent": "My-Schema-Agent"},
 * otherwise we use the first active agent of the fitting type
 *
 * @author  Christoph Kappestein <christoph.kappestein@gmail.com>
 * @license http://www.apache.org/licenses/LICENSE-2.0
 * @link    https://www.fusio-project.org
 */
readonly class ArchitectExecutor
{
    public function __construct(
        private Service\Agent\Sender $sender,
        private Table\Agent $agentTable,
        private Table\Schema $schemaTable,
        private Table\Operation $operationTable,
        private Service\Operation $operationService,
        private Service\System\ContextFactory $contextFactory,
        private ObjectMapperInterface $objectMapper,
        private SchemaExecutor $schemaExecutor,
        private ActionExecutor $actionExecutor,
        private DatabaseExecutor $databaseExecutor,
        private ConnectionResolver $connectionResolver,
    ) {
    }

    public function execute(Blueprint $model, Table\Generated\AgentRow $architect, ?int $connectionId, ContextInterface $context, StepLogger $logger): Message
    {
        $schemaAgentId = $this->resolveAgent($architect, 'schemaAgent', Table\Agent::TYPE_SCHEMA, $context);
        $actionAgentId = $this->resolveAgent($architect, 'actionAgent', Table\Agent::TYPE_ACTION, $context);
        $databaseAgentId = $this->resolveAgent($architect, 'databaseAgent', Table\Agent::TYPE_DATABASE, $context);

        if ($schemaAgentId === null || $actionAgentId === null || $databaseAgentId === null) {
            $logger->log('Resolve agents', false, 'Could not find a schema, action or database agent');

            return MessageFactory::error('Could not find a schema, action or database agent, please make sure that these agents exist');
        }

        $execution = new ArchitectExecution($this->connectionResolver->getName($connectionId, $context));

        $database = $model->getDatabase();
        if (!empty($database) && !$logger->isCanceled()) {
            $this->executeDatabase($database, $databaseAgentId, $connectionId, $context, $logger, $execution);
        }

        $operations = $model->getOperations() ?? [];
        $created = 0;
        foreach ($operations as $operation) {
            if ($logger->isCanceled()) {
                $execution->addError('the task was canceled');
                break;
            }

            $name = $operation->getName() ?? '';

            try {
                if ($this->executeOperation($operation, $schemaAgentId, $actionAgentId, $context, $logger, $execution)) {
                    $created++;
                }
            } catch (Throwable $e) {
                $logger->log('Operation: ' . $name, false, $e->getMessage());
                $execution->addError($name . ': ' . $e->getMessage());
            }
        }

        $total = count($operations);
        $errors = $execution->getErrors();
        if (count($errors) === 0) {
            return MessageFactory::success('Successfully executed blueprint, created ' . $created . ' of ' . $total . ' operations');
        }

        return MessageFactory::error('Executed blueprint, created ' . $created . ' of ' . $total . ' operations, the following errors occurred: ' . implode(', ', $errors));
    }

    private function executeDatabase(string $database, int $databaseAgentId, ?int $connectionId, ContextInterface $context, StepLogger $logger, ArchitectExecution $execution): void
    {
        try {
            $payload = $this->invokeObjectAgent($databaseAgentId, $this->withConnection($database, $execution), $context);
            $model = $this->objectMapper->read($payload, SchemaSource::fromClass(Database::class));

            $logger->log('Database agent request', true);
        } catch (Throwable $e) {
            $logger->log('Database agent request', false, $e->getMessage());
            $execution->addError('database: ' . $e->getMessage());
            return;
        }

        // we continue also in case of an error since i.e. a table may already exist from a previous run
        $result = $this->databaseExecutor->execute($model, $connectionId, $context, $logger);
        if ($result->getSuccess() !== true) {
            $execution->addError('database: ' . $result->getMessage());
        }
    }

    private function executeOperation(BlueprintOperation $operation, int $schemaAgentId, int $actionAgentId, ContextInterface $context, StepLogger $logger, ArchitectExecution $execution): bool
    {
        $name = $operation->getName() ?? '';

        $incoming = null;
        $rawIncoming = $operation->getIncoming();
        if (!empty($rawIncoming) && $rawIncoming !== 'Empty') {
            $incoming = $this->resolveSchema($rawIncoming, $schemaAgentId, $context, $logger, $execution);
            if ($incoming === null) {
                $execution->addError($name . ': could not generate incoming schema "' . $this->getName($rawIncoming) . '"');
                return false;
            }
        }

        $outgoing = null;
        $rawOutgoing = $operation->getOutgoing();
        if (!empty($rawOutgoing) && $rawOutgoing !== 'Empty') {
            $outgoing = $this->resolveSchema($rawOutgoing, $schemaAgentId, $context, $logger, $execution);
            if ($outgoing === null) {
                $execution->addError($name . ': could not generate outgoing schema "' . $this->getName($rawOutgoing) . '"');
                return false;
            }
        }

        $action = $this->resolveAction($operation, $actionAgentId, $context, $logger, $execution);
        if ($action === null) {
            $execution->addError($name . ': could not generate action "' . $this->getName($operation->getAction() ?? '') . '"');
            return false;
        }

        $parameters = [];
        foreach ($operation->getParameters() ?? [] as $parameter) {
            $parameterName = $parameter->getName();
            if (empty($parameterName)) {
                continue;
            }

            $schema = new OperationSchema();
            $schema->setType($parameter->getType());
            $schema->setDescription($parameter->getDescription());
            $parameters[$parameterName] = $schema;
        }

        $userContext = $this->contextFactory->newActionContext($context);

        $existing = $this->operationTable->findOneByTenantAndName($userContext->getTenantId(), $userContext->getCategoryId(), $name);
        if ($existing instanceof Table\Generated\OperationRow && $existing->getStatus() === Table\Operation::STATUS_ACTIVE) {
            $update = new OperationUpdate();
            $this->fillOperation($update, $operation, $parameters, $incoming, $outgoing, $action);

            $this->operationService->update('' . $existing->getId(), $update, $userContext);

            $logger->log('Operation update: ' . $name, true);
        } else {
            $create = new OperationCreate();
            $this->fillOperation($create, $operation, $parameters, $incoming, $outgoing, $action);

            $this->operationService->create($create, $userContext);

            $logger->log('Operation create: ' . $name, true);
        }

        return true;
    }

    /**
     * @param array<string, OperationSchema> $parameters
     */
    private function fillOperation(OperationCreate|OperationUpdate $target, BlueprintOperation $operation, array $parameters, ?string $incoming, ?string $outgoing, string $action): void
    {
        $target->setName($operation->getName());
        $target->setActive(true);
        $target->setPublic($operation->getPublic() ?? false);
        $target->setStability(1);
        $target->setDescription($operation->getDescription());
        $target->setHttpMethod($operation->getHttpMethod());
        $target->setHttpPath($operation->getHttpPath());
        $target->setHttpCode($operation->getHttpCode());
        $target->setParameters(OperationParameters::fromArray($parameters));
        $target->setIncoming($incoming);
        $target->setOutgoing($outgoing);
        $target->setAction($action);
    }

    private function resolveSchema(string $prompt, int $schemaAgentId, ContextInterface $context, StepLogger $logger, ArchitectExecution $execution): ?string
    {
        if ($prompt === 'Message') {
            return 'schema://Message';
        }

        // a schema name can be used by multiple operations, we generate every schema only once per blueprint since
        // otherwise a later agent call would overwrite the schema which was already assigned to a previous operation
        $name = $this->getName($prompt);
        $cached = $execution->getSchema($name);
        if ($cached !== null) {
            return $cached;
        }

        // the architect references an existing schema by its plain name (without the "NAME:" prefix), in this case we
        // reuse the schema as it is and do not invoke the schema agent which would overwrite the schema
        if (!$this->hasNamePrefix($prompt) && preg_match('/^[A-Za-z0-9_-]+$/', $name)) {
            $userContext = $this->contextFactory->newActionContext($context);
            $existing = $this->schemaTable->findOneByTenantAndName($userContext->getTenantId(), $userContext->getCategoryId(), $name);
            if ($existing instanceof Table\Generated\SchemaRow && $existing->getStatus() === Table\Schema::STATUS_ACTIVE) {
                $uri = 'schema://' . $existing->getName();
                $execution->setSchema($name, $uri);
                return $uri;
            }
        }

        try {
            $payload = $this->invokeObjectAgent($schemaAgentId, $prompt, $context);
            $model = $this->objectMapper->read($payload, SchemaSource::fromClass(Schema::class));

            $logger->log('Schema agent request: ' . $name, true);
        } catch (Throwable $e) {
            $logger->log('Schema agent request: ' . $name, false, $e->getMessage());
            return null;
        }

        $result = $this->schemaExecutor->execute($model, $context, $logger);
        if ($result->getSuccess() !== true || empty($model->getName())) {
            return null;
        }

        $uri = 'schema://' . $model->getName();
        $execution->setSchema($name, $uri);

        return $uri;
    }

    private function resolveAction(BlueprintOperation $operation, int $actionAgentId, ContextInterface $context, StepLogger $logger, ArchitectExecution $execution): ?string
    {
        $name = $this->getName($operation->getAction() ?? '');

        try {
            $content = $this->invokeTextAgent($actionAgentId, $this->buildActionPrompt($operation, $execution), $context);

            $logger->log('Action agent request: ' . $name, true);
        } catch (Throwable $e) {
            $logger->log('Action agent request: ' . $name, false, $e->getMessage());
            return null;
        }

        $result = $this->actionExecutor->execute($content, $context, $logger);
        if ($result->getSuccess() !== true) {
            return null;
        }

        $actionName = ActionParser::extractName($content);
        if (empty($actionName)) {
            return null;
        }

        return 'action://' . $actionName;
    }

    private function buildActionPrompt(BlueprintOperation $operation, ArchitectExecution $execution): string
    {
        $parameters = [];
        foreach ($operation->getParameters() ?? [] as $parameter) {
            $parameters[] = $parameter->getName() . ' (' . $parameter->getType() . ')';
        }

        $lines = [
            'Operation: ' . $operation->getHttpMethod() . ' ' . $operation->getHttpPath() . ' (' . ($operation->getPublic() ? 'public, the user may be anonymous' : 'private, requires an authenticated user') . ')',
            'Parameters: ' . (count($parameters) > 0 ? implode(', ', $parameters) : 'none'),
            'Request schema: ' . $this->getName($operation->getIncoming() ?? 'Empty'),
            'Response schema: ' . $this->getName($operation->getOutgoing() ?? 'Empty'),
            'Success status code: ' . $operation->getHttpCode(),
        ];

        $connectionName = $execution->getConnectionName();
        if (!empty($connectionName)) {
            $lines[] = 'Connection: ' . $connectionName;
        }

        return ($operation->getAction() ?? '') . "\n\n" . implode("\n", $lines);
    }

    private function withConnection(string $prompt, ArchitectExecution $execution): string
    {
        $connectionName = $execution->getConnectionName();
        if (empty($connectionName)) {
            return $prompt;
        }

        return $prompt . "\n\nConnection: " . $connectionName;
    }

    private function invokeObjectAgent(int $agentId, string $prompt, ContextInterface $context): mixed
    {
        $item = $this->invokeAgent($agentId, $prompt, $context);
        if (!$item instanceof ItemObject) {
            throw new RuntimeException('The agent returned no structured output');
        }

        return $item->getPayload();
    }

    private function invokeTextAgent(int $agentId, string $prompt, ContextInterface $context): string
    {
        $item = $this->invokeAgent($agentId, $prompt, $context);
        if (!$item instanceof ItemText) {
            throw new RuntimeException('The agent returned no text output');
        }

        return $item->getContent() ?? '';
    }

    private function invokeAgent(int $agentId, string $prompt, ContextInterface $context): ?Item
    {
        $item = new ItemText();
        $item->setType('text');
        $item->setContent($prompt);

        $input = new Input();
        $input->setItem($item);

        return $this->sender->send($agentId, $input, $context)->getItem();
    }

    private function resolveAgent(Table\Generated\AgentRow $architect, string $key, int $type, ContextInterface $context): ?int
    {
        $tenantId = $context->getTenantId();
        $categoryId = $context->getUser()->getCategoryId();

        $metadata = $architect->getMetadata();
        if (!empty($metadata)) {
            $data = Parser::decodeAsArray($metadata);
            $value = $data[$key] ?? null;
            if (is_string($value) || is_int($value)) {
                $identifier = is_int($value) || ctype_digit($value) ? '' . $value : '~' . $value;
                $row = $this->agentTable->findOneByIdentifier($tenantId, $categoryId, $identifier);
                if ($row instanceof Table\Generated\AgentRow && $row->getStatus() === Table\Agent::STATUS_ACTIVE) {
                    return $row->getId();
                }
            }
        }

        return $this->agentTable->findOneByTenantAndType($tenantId, $categoryId, $type)?->getId();
    }

    private function hasNamePrefix(string $prompt): bool
    {
        return (bool) preg_match('/^\s*NAME:/', $prompt);
    }

    private function getName(string $prompt): string
    {
        if (preg_match('/^\s*NAME:\s*([^.\s]+)\s*\./', $prompt, $matches)) {
            return $matches[1];
        }

        return trim($prompt);
    }
}
