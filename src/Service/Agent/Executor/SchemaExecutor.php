namespace Fusio\Impl\Service\Agent\Executor;

use Fusio\Engine\ContextInterface;
use Fusio\Impl\Service;
use Fusio\Impl\Service\Agent\Task\StepLogger;
use Fusio\Impl\Table;
use Fusio\Model\Agent\Schema;
use Fusio\Model\Backend\SchemaCreate;
use Fusio\Model\Backend\SchemaSource;
use Fusio\Model\Backend\SchemaUpdate;
use Fusio\Model\Common\Message;
use PSX\Json\Parser;
use Throwable;
use TypeAPI\Editor\Generator;
use TypeAPI\Editor\Model\Document;

/**
 * Creates or updates the schema which was generated by the schema agent
 *
 * @author  Christoph Kappestein <christoph.kappestein@gmail.com>
 * @license http://www.apache.org/licenses/LICENSE-2.0
 * @link    https://www.fusio-project.org
 */
readonly class SchemaExecutor
{
    public function __construct(
        private Service\Schema $schemaService,
        private Table\Schema $schemaTable,
        private Service\System\ContextFactory $contextFactory,
    ) {
    }

    public function execute(Schema $model, ContextInterface $context, StepLogger $logger): Message
    {
        $name = $model->getName();
        if (empty($name)) {
            $logger->log('Schema create', false, 'The schema agent returned no schema name');

            return MessageFactory::error('The schema agent returned no schema name');
        }

        $userContext = $this->contextFactory->newActionContext($context);

        $specification = new Generator()->toModel(Document::from(Parser::encode($model)));
        $source = SchemaSource::from($specification->jsonSerialize());

        try {
            $existing = $this->schemaTable->findOneByTenantAndName($userContext->getTenantId(), $userContext->getCategoryId(), $name);
            if ($existing instanceof Table\Generated\SchemaRow && $existing->getStatus() === Table\Schema::STATUS_ACTIVE) {
                $update = new SchemaUpdate();
                $update->setSource($source);

                $id = $this->schemaService->update('' . $existing->getId(), $update, $userContext);

                $logger->log('Schema update: ' . $name, true);

                return MessageFactory::success('Schema successfully updated', $id);
            } else {
                $create = new SchemaCreate();
                $create->setName($name);
                $create->setSource($source);

                $id = $this->schemaService->create($create, $userContext);

                $logger->log('Schema create: ' . $name, true);

                return MessageFactory::success('Schema successfully created', $id);
            }
        } catch (Throwable $e) {
            $logger->log('Schema create: ' . $name, false, $e->getMessage());

            return MessageFactory::error($e->getMessage());
        }
    }
}
