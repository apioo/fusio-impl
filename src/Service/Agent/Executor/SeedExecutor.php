namespace Fusio\Impl\Service\Agent\Executor;

use Doctrine\DBAL\Connection;
use Fusio\Engine\ConnectorInterface;
use Fusio\Engine\ContextInterface;
use Fusio\Impl\Service\Agent\Task\StepLogger;
use Fusio\Impl\Service\System\FrameworkConfig;
use Fusio\Model\Agent\Seed;
use Fusio\Model\Common\Message;
use Throwable;

/**
 * Inserts the rows which were generated by the seed agent
 *
 * @author  Christoph Kappestein <christoph.kappestein@gmail.com>
 * @license http://www.apache.org/licenses/LICENSE-2.0
 * @link    https://www.fusio-project.org
 */
readonly class SeedExecutor
{
    public function __construct(
        private ConnectorInterface $connector,
        private ConnectionResolver $connectionResolver,
        private FrameworkConfig $frameworkConfig,
    ) {
    }

    public function execute(Seed $model, ?int $connectionId, ContextInterface $context, StepLogger $logger): Message
    {
        if (!$this->frameworkConfig->isConnectionEnabled()) {
            return MessageFactory::error('Database is not enabled, please change the setting "fusio_connection" at the configuration.php to "true" in order to activate the database');
        }

        $connection = $this->connector->getConnection($this->connectionResolver->resolve($connectionId, $context));
        if (!$connection instanceof Connection) {
            return MessageFactory::error('Provided connection is not a SQL connection');
        }

        $schemaManager = $connection->createSchemaManager();

        $success = 0;
        $errors = [];
        foreach ($model->getTables() ?? [] as $table) {
            if ($logger->isCanceled()) {
                break;
            }

            $tableName = $table->getName() ?? '';
            $columns = $table->getColumns() ?? [];

            if (!$this->isValidIdentifier($tableName) || !$schemaManager->tablesExist([$tableName])) {
                $logger->log('Insert seed: ' . $tableName, false, 'Table does not exist');
                $errors[] = $tableName . ': Table does not exist';
                continue;
            }

            foreach ($columns as $column) {
                if (!$this->isValidIdentifier($column)) {
                    $logger->log('Insert seed: ' . $tableName, false, 'Invalid column name ' . $column);
                    $errors[] = $tableName . ': Invalid column name ' . $column;
                    continue 2;
                }
            }

            $inserted = 0;
            $connection->beginTransaction();

            try {
                foreach ($table->getRows() ?? [] as $row) {
                    $values = $row->getValues() ?? [];
                    if (count($values) !== count($columns)) {
                        throw new \RuntimeException('Row ' . ($inserted + 1) . ' contains ' . count($values) . ' values but the table has ' . count($columns) . ' columns');
                    }

                    $data = [];
                    foreach ($columns as $index => $column) {
                        $data[$connection->quoteIdentifier($column)] = $values[$index];
                    }

                    $connection->insert($connection->quoteIdentifier($tableName), $data);
                    $inserted++;
                }

                $connection->commit();

                $logger->log('Insert seed: ' . $tableName, true, 'Inserted ' . $inserted . ' rows');
                $success += $inserted;
            } catch (Throwable $e) {
                $connection->rollBack();

                $logger->log('Insert seed: ' . $tableName, false, $e->getMessage());
                $errors[] = $tableName . ': ' . $e->getMessage();
            }
        }

        if (count($errors) === 0) {
            return MessageFactory::success('Successfully inserted ' . $success . ' rows');
        }

        $message = '';
        if ($success > 0) {
            $message .= 'Successfully inserted ' . $success . ' rows, ';
        }

        $message .= count($errors) . ' tables produced the following errors: ' . implode(', ', $errors);

        return MessageFactory::error($message);
    }

    private function isValidIdentifier(string $name): bool
    {
        return (bool) preg_match('/^[A-Za-z0-9_]{1,64}$/', $name);
    }
}
