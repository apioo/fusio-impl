namespace Fusio\Impl\Service\Agent\Executor;

use Fusio\Engine\ContextInterface;
use Fusio\Impl\Service;
use Fusio\Impl\Service\Agent\Task\StepLogger;
use Fusio\Impl\Table;
use Fusio\Model\Backend\ActionConfig;
use Fusio\Model\Backend\ActionCreate;
use Fusio\Model\Backend\ActionUpdate;
use Fusio\Model\Common\Message;
use Throwable;

/**
 * Creates or updates the action which was generated by the action agent
 *
 * @author  Christoph Kappestein <christoph.kappestein@gmail.com>
 * @license http://www.apache.org/licenses/LICENSE-2.0
 * @link    https://www.fusio-project.org
 */
readonly class ActionExecutor
{
    public const ACTION_CLASS = 'Fusio.Adapter.Worker.Action.WorkerPHPLocal';

    public function __construct(
        private Service\Action $actionService,
        private Table\Action $actionTable,
        private Service\System\ContextFactory $contextFactory,
    ) {
    }

    public function execute(string $content, ContextInterface $context, StepLogger $logger): Message
    {
        $name = ActionParser::extractName($content);
        if (empty($name)) {
            $logger->log('Action create', false, 'The action agent returned no action name');

            return MessageFactory::error('The action agent returned no action name');
        }

        $code = ActionParser::extractCode($content);
        if (empty($code)) {
            $logger->log('Action create: ' . $name, false, 'The action agent returned no PHP code');

            return MessageFactory::error('The action agent returned no PHP code');
        }

        $userContext = $this->contextFactory->newActionContext($context);

        try {
            $existing = $this->actionTable->findOneByTenantAndName($userContext->getTenantId(), $userContext->getCategoryId(), $name);
            if ($existing instanceof Table\Generated\ActionRow && $existing->getStatus() === Table\Action::STATUS_ACTIVE) {
                // we only replace the code and keep all other config values
                $config = Service\Action::unserializeConfig($existing->getConfig()) ?? [];
                $config['code'] = $code;

                $update = new ActionUpdate();
                $update->setConfig(ActionConfig::fromArray($config));

                $id = $this->actionService->update('' . $existing->getId(), $update, $userContext);

                $logger->log('Action update: ' . $name, true);

                return MessageFactory::success('Action successfully updated', $id);
            } else {
                $create = new ActionCreate();
                $create->setName($name);
                $create->setClass(self::ACTION_CLASS);
                $create->setConfig(ActionConfig::fromArray(['code' => $code]));

                $id = $this->actionService->create($create, $userContext);

                $logger->log('Action create: ' . $name, true);

                return MessageFactory::success('Action successfully created', $id);
            }
        } catch (Throwable $e) {
            $logger->log('Action create: ' . $name, false, $e->getMessage());

            return MessageFactory::error($e->getMessage());
        }
    }
}
