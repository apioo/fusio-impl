namespace Fusio\Impl\Service\Agent\Executor;

use Fusio\Engine\ContextInterface;
use Fusio\Engine\Inflection\ClassName;
use Fusio\Engine\ProcessorInterface;
use Fusio\Engine\Request;
use Fusio\Impl\Backend\Action\Connection\Database\Table\Create as TableCreate;
use Fusio\Impl\Service\Agent\Task\StepLogger;
use Fusio\Model\Agent\Database;
use Fusio\Model\Backend\DatabaseTable;
use Fusio\Model\Common\Message;
use PSX\Schema\ObjectMapperInterface;
use PSX\Schema\SchemaSource;
use Throwable;

/**
 * Creates all tables which were generated by the database agent. To create the tables we reuse the backend action
 * which is also used by the "create table" endpoint, so that the same validation rules apply
 *
 * @author  Christoph Kappestein <christoph.kappestein@gmail.com>
 * @license http://www.apache.org/licenses/LICENSE-2.0
 * @link    https://www.fusio-project.org
 */
readonly class DatabaseExecutor
{
    public function __construct(
        private ProcessorInterface $processor,
        private ObjectMapperInterface $objectMapper,
        private ConnectionResolver $connectionResolver,
    ) {
    }

    public function execute(Database $model, ?int $connectionId, ContextInterface $context, StepLogger $logger): Message
    {
        $tables = $model->getTables() ?? [];
        if (count($tables) === 0) {
            $logger->log('Table create', true, 'The database agent returned no tables, all tables exist already');

            return MessageFactory::success('No tables to create');
        }

        $connectionId = $this->connectionResolver->resolve($connectionId, $context);
        $action = 'php+class://' . ClassName::serialize(TableCreate::class);

        $success = 0;
        $errors = [];
        foreach ($tables as $table) {
            if ($logger->isCanceled()) {
                break;
            }

            $name = $table->getName() ?? '';

            try {
                $payload = $this->objectMapper->read($this->objectMapper->write($table), SchemaSource::fromClass(DatabaseTable::class));
                $request = new Request(['connection_id' => '' . $connectionId], $payload, new Request\RpcRequestContext('agent.database'));

                $this->processor->execute($action, $request, $context, false);

                $logger->log('Table create: ' . $name, true);
                $success++;
            } catch (Throwable $e) {
                $logger->log('Table create: ' . $name, false, $e->getMessage());
                $errors[] = $name . ': ' . $e->getMessage();
            }
        }

        if (count($errors) === 0) {
            return MessageFactory::success('Successfully created ' . $success . ' tables');
        }

        $message = '';
        if ($success > 0) {
            $message .= 'Successfully created ' . $success . ' tables, ';
        }

        $message .= count($errors) . ' tables produced the following errors: ' . implode(', ', $errors);

        return MessageFactory::error($message);
    }
}
